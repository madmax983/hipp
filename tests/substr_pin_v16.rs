#[test]
fn substr_extreme_arguments_match_the_pin() {
    block_on(async {
        let mut db = Connection::open(MemStorage::new(), Config::default())
            .await
            .expect("open");
        for (args, text, hex) in PIN {
            let sql = format!(
                "SELECT substr('abcdefghijklmnopqrstuvwxyz', {args}), \
                 hex(substr(x'000102030405060708090a0b0c0d0e0f10111213141516171819', {args}))"
            );
            let mut st = db.prepare(&sql).await.expect("prepare");
            assert_eq!(st.step().await.expect("step"), Step::Row, "{sql}");
            let got_text = st.column_bytes(0).unwrap_or_default().to_vec();
            let got_hex = st.column_bytes(1).unwrap_or_default().to_vec();
            assert_eq!(
                (
                    String::from_utf8_lossy(&got_text),
                    String::from_utf8_lossy(&got_hex)
                ),
                (
                    std::borrow::Cow::Borrowed(*text),
                    std::borrow::Cow::Borrowed(*hex)
                ),
                "substr(X, {args})"
            );
        }
    });
}
